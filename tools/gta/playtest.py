"""Keep the F7 development session available until the selected GTA process exits.

Continuous world streaming follows the player across supported static geometry.
A failed attempt releases its transports before a grounded on-foot retry.
No keyboard events or player-position writes are generated by this supervisor.
"""
import argparse
import ctypes
from concurrent.futures import ThreadPoolExecutor
from ctypes import wintypes
import json
import math
from pathlib import Path
from queue import Empty, SimpleQueue
import subprocess
import sys
from threading import Event
import time

from native.inspect_state import Observer
import startup_status


def eligible(state, origin=None, *, world_stream=False):
    ready = (state['control_eligible'] and state['flags'] & 8
            and state['grounded'] and state['ped_motion_flags'] == 1
            and not state['flags'] & (64 | 256))
    if world_stream:
        return bool(ready and state['area'] == state['ped_area'])
    return bool(ready and state['area'] == 0 and origin is not None
                and math.dist(state['position'][:2], origin[:2]) < 96)


def child_command(pid, scene, report, *, world_stream=False, continuous=False, stop_file=None, f7_baseline=None):
    command = [sys.executable, '-B', str(Path(__file__).with_name('live_session.py')),
               '--pid', str(pid), '--report', str(report), '--camera', '--hud']
    if scene is not None:
        command.extend(('--scene', str(scene)))
    if world_stream:
        command.append('--world-stream')
    if continuous:
        command.append('--continuous')
        if f7_baseline is not None:
            command.extend(('--f7-baseline', str(f7_baseline)))
    if stop_file is not None:
        command.extend(('--stop-file', str(stop_file)))
    return command


def alive(observer):
    code = wintypes.DWORD()
    return bool(observer.api.GetExitCodeProcess(observer.process, ctypes.byref(code))) and code.value == 259


def wait_for_owned_child(child):
    try:
        return child.wait(timeout=3)
    except subprocess.TimeoutExpired:
        child.kill()
        return child.wait(timeout=5)


def prepare_world(observer, directory, status):
    """Check/rebuild static map data before any engine child can use it."""
    import map_preparation
    cancelled, progress = Event(), SimpleQueue()
    stage, details = 'checking_sources', {}
    status('loading', map_stage=stage)
    with ThreadPoolExecutor(max_workers=1, thread_name_prefix='gta-map-preparation') as pool:
        future = pool.submit(map_preparation.prepare, observer.exe.parent, directory / 'map-preparation',
            progress=lambda phase, **fields: progress.put((phase, fields)), stopped=cancelled.is_set)
        try:
            while not future.done():
                if not alive(observer) or (directory / 'STOP').exists():
                    cancelled.set()
                    status('stopped' if (directory / 'STOP').exists() else 'game_closed')
                    return False
                try:
                    while True:
                        stage, details = progress.get_nowait()
                except Empty:
                    pass
                # Keep the overlay alive while hashing or compiling in the worker.
                status('loading', map_stage=stage, map_progress=details)
                time.sleep(.1)
            result = future.result()
            (directory / 'map-preparation.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
            return True  # The engine's ready marker, not this result, enables the Ready notice.
        except BaseException as error:
            cancelled.set()
            status('map_preparation_failed', error=str(error))
            raise


def supervise(pid, scene, directory, *, world_stream=False, continuous=False):
    directory.mkdir(parents=True, exist_ok=False)
    origin = None if world_stream else json.loads(scene.with_suffix('.json').read_bytes())['coordinates']['origin_gta']
    observer = Observer(pid)
    try:
        display = startup_status.connect(observer)
    except BaseException:
        observer.close()
        raise
    child = None
    attempt = 0
    last_status = None
    f7_baseline = None
    map_prepared = False

    def status(phase, **details):
        nonlocal last_status
        if display is not None:
            display.update(phase)
        value = dict(phase=phase, pid=pid, creation_100ns=observer.created,
                     attempt=attempt, **details)
        if value != last_status:
            temporary = directory / 'status.tmp'
            temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')
            temporary.replace(directory / 'status.json')
            last_status = value

    try:
        while alive(observer) and not (directory / 'STOP').exists():
            try:
                state = observer.read()
            except ValueError:
                status('waiting_for_game')
                time.sleep(.25)
                continue
            if continuous and f7_baseline is None:
                # The user's switch survives unavailable scenes and child restarts.
                f7_baseline = state['f7_requests']
            if world_stream and not map_prepared:
                if not prepare_world(observer, directory, status):
                    return
                map_prepared = True
                continue  # Read fresh control/position state after preparation.
            if not eligible(state, origin, world_stream=world_stream):
                status('waiting_for_on_foot' if world_stream else 'waiting_for_on_foot_start_area')
                time.sleep(.25)
                continue
            attempt += 1
            report = directory / f'attempt-{attempt:04}.jsonl'
            command = child_command(pid, scene, report, world_stream=world_stream, continuous=continuous,
                                    stop_file=directory / 'STOP', f7_baseline=f7_baseline)
            status('starting_gameplay')
            with report.with_suffix('.stdout.txt').open('x') as output, report.with_suffix('.stderr.txt').open('x') as errors:
                child = subprocess.Popen(command, stdout=output, stderr=errors,
                                         creationflags=subprocess.CREATE_NO_WINDOW)
                ready, accepted = report.with_suffix('.ready'), report.with_suffix('.accepted')
                while (child.poll() is None and alive(observer)
                       and not (directory / 'STOP').exists()):
                    status('ready' if ready.exists() else 'starting_gameplay', report=str(report),
                           ready=ready.read_text(encoding='utf-8') if ready.exists() else '',
                           last_accepted=accepted.read_text(encoding='utf-8') if accepted.exists() else '')
                    time.sleep(.1)
                result = wait_for_owned_child(child)
                child = None
            status('restarting', previous_exit=result, report=str(report))
            time.sleep(.5)
        status('stopped' if (directory / 'STOP').exists() else 'game_closed')
    finally:
        try:
            if child is not None and child.poll() is None:
                (directory / 'STOP').touch()
                wait_for_owned_child(child)
        finally:
            if display is not None:
                display.close()
            observer.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pid', type=int, required=True)
    parser.add_argument('--scene', type=Path)
    parser.add_argument('--world-stream', action='store_true', help='Prepare local world.db collision tiles across the GTA map')
    parser.add_argument('--continuous', action='store_true', help='Keep each source session alive until toggled off with J or process shutdown')
    parser.add_argument('--directory', type=Path, required=True)
    args = parser.parse_args()
    if (args.pid <= 0 or not args.directory.is_absolute() or args.directory.exists()
            or (args.scene is not None and not args.scene.is_absolute())
            or (args.scene is None and not args.world_stream)):
        parser.error('Use a positive PID, --world-stream or an absolute scene path, and a new absolute log directory')
    supervise(args.pid, args.scene, args.directory, world_stream=args.world_stream, continuous=args.continuous)


if __name__ == '__main__':
    main()
